# 학생, 과목 점수 조회
# 1. 이름, 과목 입력
# 2. 해당 학생의 해당 과목 점수 출력

# 학생, 과목, 점수 중첩 딕셔너리
students = {
    "윤서": {"수학": 85, "영어": 90, "과학": 78},
    "지우": {"수학": 92, "영어": 88},
    "민준": {"수학": 65, "영어": 70, "과학": 80, "역사": 75},
}

# 이름, 과목 입력
name = input()
subject = input()

# .get으로 존재 여부 확인 후 결과 출력 / 없을 경우 없음 출력
print(students.get(name, {}).get(subject, "없음"))