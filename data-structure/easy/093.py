# 두 set의 치집합
# 1. 시나리오 번호 입력
# 2. 차집합 정렬
# 3. 결과 출력

# 2개의 set
a_sets = [
    {"윤서", "지우", "민준", "도윤"},
    {"a", "b", "c", "d"},
    {"x", "y"},
]
b_sets = [
    {"지우", "도윤", "예준"},
    {"c", "d", "e"},
    {"x", "y", "z"},
]

# 시나리오 번호 입력
t = int(input())
a = a_sets[t]
b = b_sets[t]

# 정렬된 차집합 출력
print(' '.join(sorted(a - b)))