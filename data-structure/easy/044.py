# 각 정수의 자릿수 길이
# 1. 시나리오 번호 입력
# 2. 리스트 순회 및 자릿수 계산
# 3. 결과 출력

# 3차원 리스트
data_sets = [
    [1, 23, 456, 7890, 5, 100, 9999],
    [1, 5, 9],
    [10000],
]

# 시나리오 번호 입력
t = int(input())
nums = data_sets[t]

# 리스트 순회 컴프리헨션
digits = [len(str(num)) for num in nums]    # 리스트 순회 / 요소를 문자열로 변환 후 자릿수 계산

# 결과 출력
print(*digits)  # 언패킹으로 공백 구분 출력