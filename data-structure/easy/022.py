# 첫, 끝 원소 제외
# 1. 시나리오 번호 입력
# 2. 첫 원소와 마지막 원소를 제외 / 가운데 부분만 출력

# 3차원 리스트
data_sets = [
    [10, 20, 30, 40, 50, 60, 70, 80],
    [1, 2, 3, 4, 5],
    [10, 20],
]

# 시나리오 번호 입력
t = int(input())
data = data_sets[t]

# 슬라이싱으로 인덱스 1부터 시작 / 인덱스 -1 까지로 첫 원소와 마지막 원소 제외
print(" ".join(map(str, data[1:-1])))