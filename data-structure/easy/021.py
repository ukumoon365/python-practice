# 홀수 위치 원소 추출
# 1. 시나리오 번호 입력
# 2. 선택된 시나리오 리스트의 홀수만 출력 / 값 사이 공백으로 구분
#    [1::2]로 홀수만 출력

# 3차원 리스트
data_sets = [
    [10, 11, 20, 21, 30, 31, 40, 41, 50, 51],
    [1, 2, 3, 4, 5],
    [100],
]

# 시나리오 번호 입력
t = int(input())
data = data_sets[t]

# 해당 시나리오 홀수만 출력
print(" ".join(map(str, data[1::2])))