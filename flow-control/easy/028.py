# 시험 합격
# 1. 점수 입력
# 2. 필기 점수에 따른 합격 여부 판별
# 3. 필기 합격시 실기 점수 입력
# 4. 실기 점수에 따른 합격 여부 판별
# 5. 결과 출력

# 필기 점수 입력
written = int(input())

# 필기 점수에 따른 합격 여부 판별 if문
if written >= 60:
    print("필기 합격!")
    practical = int(input()) # 실기 점수 입력 받기
    if practical >=70: # 실기 점수에 따른 합격 여부 판별 if문
        print("최종 합격입니다!")
    else: # 실기 점수 70점 미만
        print("실기 불합격입니다. 실기 재시험 대상입니다.")
else: # 필기 60점 미만
    print("필기 불합격입니다. 필기부터 다시 응시하세요.")