# 숫자 뒤집기
# 1. 정수 입력
# 2. 자릿수가 1이 될 때까지 반복
#   1) 자릿수 값 계산
#   2) 자릿수 값 저장
#   3) 자릿수 빼기
# 3. 결과 출력

# 정수 입력
num = int(input())
# 결과값 저장 변수 초기화
reverse = 0

# 자릿수가 1이 될 때까지 반복
while num > 0:
    digit = num % 10          # 10으로 나누어 자릿수 구하기
    reverse = reverse * 10 + digit  # 위에서 구한 자리수를 더해서 추가
    num //= 10                # 10으로 나누어 자릿수 줄이기

# 결과 출력
print(f"뒤집은 숫자: {reverse}")