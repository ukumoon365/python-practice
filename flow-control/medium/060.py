# 구구단 일부 출력
# 1. 시작 단, 끝 단을 입력
# 2. 시작 단부터 끝 단까지 반복문을 통해 구구단을 출력
#    각 단의 시작에 --- N단 ---을 출력
#    이어서 N x 1 = N 형식으로 1~9까지
#    각 단이 끝나면 빈 줄을 한 줄 출력



# 시작 단, 끝 단 입력
a, b = map(int, input().split())

# 구구단 출력 for문
for i in range(a, b + 1):
    print(f"--- {i}단 ---")                 # 각 단의 시작에 출력
    for dan in range(1, 10):    
        print(f"{i} x {dan} = {i*dan}")     # 구구단 계산 후 출력
    print()     # 각 단이 끝나면 빈 줄 출력